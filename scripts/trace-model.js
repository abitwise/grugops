// trace-model.ts — the one trace model (phase 37, plan 37-06, SPLIT-03, D-01, D-03).
//
// WHAT IT IS. The pure part of the requirement→code→test→release trace: how a note ref is classified into a
// trace column, how the refs of every note are merged into one row per ticket, the text of one ticket's trace
// file and of the one-line-per-ticket index, the file name of a ticket's trace, and the plan of the whole
// rendered tree (repository-relative path to text). It also owns HAND_TRACE_PATTERNS, the four patterns the
// kit's hand-trace scan (plan 37-18) looks for, and HAND_TRACE_WRITE_VERBS, the verb list two of them share
// (plan 37-32), because the index it renders is the text that scan reads.
//
// Plan 37-07 adds the comparison: the owned-entry rule for the trace directory (ownedTraceEntries), the
// case-fold collision groups (caseFoldCollisions), the generated-header test (isGeneratedTraceText) and the
// tree comparison (compareTraceTree), which takes the text reader and the directory lister as parameters.
//
// Plan 37-21 adds the one completeness predicate (traceReadFailures, TRACE_TRUST_SKIP_ARMS) and the gated plan
// (planCompleteTraceTree): a plan exists only for a complete note read, so a failed task or a note skipped
// under an I/O arm stops the render and the compare instead of reading as a ticket with no notes (CR-01).
//
// Plan 37-22 takes the ticket answer from the board grammar (D-17, WR-01): isTicketRef, classifyRef,
// buildTraceRows and planCompleteTraceTree take scripts/board-model.ts isTicketId as a parameter, and
// traceFileNameRefusals checks every planned file name before the render's first write.
//
// WHO USES IT. It is embedded, by scripts/generate-runnable-embeds.ts, into the host runnable
// scripts/runnable-ref/trace-render.ts (this plan) and into state-check (plan 37-09), so the render and the
// freshness comparison run the same code. scripts/trace-render.ts imports it for its own monolithic render
// until plan 37-08 turns that file into a wrapper.
//
// NO IMPORTS. The generator embeds only declarations whose closure reaches `node:` builtins, and a host has no
// kit. So this module imports nothing: the note reader is passed in (collectTraceNotes takes the listing and
// the per-task read as parameters), the text reader is passed in (compareTraceTree takes it with the
// directory lister), and every state path is passed in (planTraceTree and compareTraceTree take the index
// path and the trace directory). It never imports scripts/context-io.ts; the seal check stays that module's.
//
// BYTES DO NOT DEPEND ON THE MACHINE. Every sort compares UTF-16 code units (compareCodeUnits), never
// localeCompare, so two machines with different locales render identical bytes. Every generated file starts
// with the same command-neutral header line, so a render in this repository and on a host are identical.
//
// Voice: clear professional voice (CLAUDE.md hard rule): this is a trace surface.
/** The first line of every generated trace file. It names no command, so every host renders the same bytes. */
export const TRACE_GENERATED_HEADER = "<!-- GENERATED by grugops trace-render from published note refs — do not hand-edit -->";
