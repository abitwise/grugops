/** The one alternation of HAND_TRACE_WRITE_VERBS, made once and used by patterns 1 and 4. */
const WRITE_VERB = `(?:${HAND_TRACE_WRITE_VERBS.join("|")})`;
/**
 * Up to 120 characters that are not a dot, or are a dot followed by a non-space character. A path's dot
 * (`./memory-bank/...`, `traceability.md`) is followed by a non-space character and is crossed; a sentence-ending dot
 * is followed by a space or the end of the text and stops the bound.
 */
const PATTERN_1_BOUND = String.raw `(?:[^.]|\.(?=\S)){0,120}`;
/**
 * Pattern 4's exclusions, each reasoned from the truth "no kit file tells an agent to write the trace by hand".
 */
const PATTERN_4 = [
    // A negated verb is a prohibition: it tells the agent not to write ("No step edits a trace file", "Never hand-edit").
    String.raw `(?<!\b(?:never|not|nothing|cannot|can't|don't|doesn't|won't) )(?<!\bno \w+ )`,
    // The renderer as the verb's subject is the render writing, not an agent ("The next trace render adds the release").
    String.raw `(?<!\brender(?:s|er)? )`,
    // The tail of a hyphenated verb is not a verb of its own: "hand-edit" is one verb, read whole or not at all.
    String.raw `(?<!-)`,
    String.raw `\b${WRITE_VERB}\b`,
    // A verb followed by "nothing" writes nothing ("adds nothing to the trace").
    String.raw `(?! nothing\b)`,
    // Lazily, up to 120 characters between the verb and the trace. None starts the word note or ref (the typed-note or
    // ref route is the sanctioned write), none starts the word because (a reason clause says what a thing is), none is a
    // newline or a semicolon (a clause bound), and none is a dot unless a non-space character follows it (a sentence end
    // stops the reach, a path's dot does not).
    String.raw `(?:(?!\b(?:notes?|refs?)\b)(?!\bbecause\b)(?:[^\n;.]|\.(?=\S))){0,120}?`,
    // The trace after a copula is a classification, not an object ("it is a trace").
    String.raw `(?<!\b(?:is|are|be|been|being) )`,
    String.raw `\b(?:the|a|an|its|this|that|each|every|ticket|tickets|ticket's)\s+trace\b`,
    // "the trace render" names the renderer, not the trace.
    String.raw `(?![ -]render)`,
].join("");
/**
 * The four hand-trace scan patterns, stated once (plan 37-18 imports them from here and keeps no copy).
 *
 * They are derived from the truth they guard (SPLIT-03, D-02; plans 37-27 and 37-32, SCAN-1): no kit file tells an
 * agent to write the trace by hand. They are not derived from the first sentences a scan caught, which is how the
 * earlier pair came to need the word "traceability" (37-VERIFICATION.md Gap 3), and how the three patterns still let
 * "Append the PR link to the trace." through (37-REVIEW.md WR-08).
 *   1. a write verb (HAND_TRACE_WRITE_VERBS) aimed at traceability: "Append to traceability.md the PR link",
 *      "Add the test path to ./memory-bank/plans/traceability.md". Its bound crosses a dot that a non-space character
 *      follows, so a path's dot no longer stops it; a sentence end still does;
 *   2. the retired hand-kept matrix shape named with the word traceability: "the traceability matrix";
 *   3. the same retired shape named without it: "the trace rows are appended", "write trace row";
 *   4. a write verb (the same list) aimed at the trace in any spelling: `the`, `a`, `an`, `its`, `this`, `that`,
 *      `each`, `every`, `ticket`, `tickets` or `ticket's` followed by the word `trace`: "Append the PR link to the
 *      trace.", "Update its trace file.", "Record the release in each ticket's trace.".
 * A row or a column exists only in that retired matrix; the rendered trace has one file per ticket and one index
 * line per ticket, so patterns 2 and 3 name a shape no rendered trace has.
 *
 * Pattern 4's exclusions, each reasoned from the same truth (scripts/trace-instructions.test.ts EXCLUSION_CONTROLS
 * holds each with a negative and a control positive):
 *   - a negated verb (`never`, `not`, `no <word>`, `nothing`, `cannot`, `can't`, `don't`, `doesn't`, `won't`
 *     before it) is a prohibition: it tells the agent not to write. It reaches only the verb it precedes;
 *   - `render`, `renders` or `renderer` as the verb's subject is the render writing, not an agent;
 *   - the tail of a hyphenated verb (`edit` in `hand-edit`) is not read as a verb of its own;
 *   - a verb followed by `nothing` writes nothing;
 *   - the words `note`, `notes`, `ref` or `refs` between the verb and the trace are the sanctioned route (a typed
 *     note whose refs the render reads), not a hand write;
 *   - a clause bound between the verb and the trace (a newline, a semicolon, a sentence-ending dot, or `because`)
 *     keeps a verb from reaching an object in another clause;
 *   - the trace after `is`, `are`, `be`, `been` or `being` is a classification ("it is a trace surface"), not an
 *     object;
 *   - `the trace render` (or `trace-render`) names the renderer, not the trace.
 * A future false hit is fixed by a new reasoned exclusion with its own negative and control, never by narrowing
 * patterns 1 to 3.
 *
 * Each is case-insensitive and none has the `g` flag, because a global RegExp carries lastIndex from one test()
 * call into the next. Every repetition is bounded (120 characters) and each step of a bounded run consumes exactly
 * one character, so a pattern's time is linear in the text times that bound; trace-instructions.test.ts holds a
 * runtime ceiling on 20,000-character adversarial inputs. The patterns are no EMBED_SPECS root and no embedded
 * closure reaches them: the host runnables never scan prose, so the list and the patterns stay in this module only.
 */
export const HAND_TRACE_PATTERNS = Object.freeze([
    new RegExp(String.raw `\b${WRITE_VERB}\b${PATTERN_1_BOUND}traceability`, "i"),
    /traceability (row|rows|matrix|column|columns)\b/i,
    /\btrace (row|rows|matrix|column|columns)\b/i,
    new RegExp(PATTERN_4, "i"),
]);
/**
 * The directory, relative to the index file's own directory, that holds one trace file per ticket. The index
 * links each ticket as `<TRACE_LINK_DIR>/<ID>.md`; scripts/trace-model.test.ts holds this equal to TRACE_DIR_REL
 * beside TRACEABILITY_REL in install/state-layout.ts.
 */
export const TRACE_LINK_DIR = "traceability";
/** Structural prefixes that are never a ticket: requirements, decisions, risks, releases, incidents, UAT. */
const RESERVED_PREFIXES = new Set(["EPIC", "FEAT", "NFR", "ADR", "RISK", "REL", "INC", "UAT"]);
/**
 * `<PREFIX>-<number>`: letters and digits starting with a letter, one hyphen, digits. It decides no ticket: it
 * only picks the column of a ref that is not one (the UAT, REL and requirement prefixes, and the
 * any-other-identifier-is-a-requirement arm of classifyRef).
 */
const ID_SHAPE = /^([A-Za-z][A-Za-z0-9]*)-(\d+)$/;
/**
 * True when `ref` is a ticket identifier: the board grammar admits it (`isTicketId`) and the text before its last
 * hyphen is not a reserved structural prefix.
 */
export function isTicketRef(ref, isTicketId) {
    return isTicketId(ref) && !RESERVED_PREFIXES.has(ref.slice(0, ref.lastIndexOf("-")));
}
/** A Tests link names a test or spec file, or an e2e path. */
function isTestRef(ref) {
    return /(^|[\/.])(test|spec)([\/.]|$)/i.test(ref) || /(^|\/)e2e(\/|$)/i.test(ref);
}
/** A Code link names a pull request (`#123`) or a source path, and is not a Tests link. */
function isCodeRef(ref) {
    if (isTestRef(ref))
        return false;
    return /^#\d+$/.test(ref) || ref.includes("/") || /\.[A-Za-z0-9]+$/.test(ref);
}
/** The five trace columns, in the order a ticket's trace file lists them. */
export const TRACE_COLUMNS = Object.freeze(["Requirement", "Code", "Tests", "UAT", "Release"]);
/**
 * The column one ref belongs to, or null for a ticket identifier (the board grammar's answer, `isTicketId`) and
 * for a ref no rule classifies.
 */
export function classifyRef(ref, isTicketId) {
    const m = ID_SHAPE.exec(ref);
    const prefix = m ? m[1].toUpperCase() : "";
    if (prefix === "UAT")
        return "UAT";
    if (prefix === "REL")
        return "Release";
    if (prefix === "NFR" || prefix === "EPIC" || prefix === "FEAT")
        return "Requirement";
    if (isTestRef(ref))
        return "Tests";
    if (isTicketRef(ref, isTicketId))
        return null;
    if (isCodeRef(ref))
        return "Code";
    // Any other ID-shaped token (a structural prefix such as ADR or RISK) is a Requirement link.
    if (m)
        return "Requirement";
    return null;
}
/** Code-unit order: the same answer on every machine, whatever its locale. */
export function compareCodeUnits(a, b) {
    return a < b ? -1 : a > b ? 1 : 0;
}
/**
 * Escape a ref before it enters a rendered line: backslash first, then pipe, then every line break flattened
 * to a space, so a ref can neither break a table nor start a new markdown line.
 */
export function traceCell(s) {
    return s.replace(/\\/g, "\\\\").replace(/\|/g, "\\|").replace(/\r?\n|\r/g, " ");
}
/**
 * One row per ticket identifier found in the notes' refs, a ticket being what the board grammar's `isTicketId`
 * admits. Every other ref on a note that names a ticket is classified into a column of that ticket's row; two
 * notes for one ticket merge their refs in first-seen order without duplicates. A note naming no ticket
 * contributes nothing. Rows are sorted by code-unit order of the id.
 */
export function buildTraceRows(notes, isTicketId) {
    const rows = new Map();
    for (const note of notes) {
        for (const ticketId of note.refs.filter((ref) => isTicketRef(ref, isTicketId))) {
            let row = rows.get(ticketId);
            if (row === undefined) {
                row = { id: ticketId, Requirement: [], Code: [], Tests: [], UAT: [], Release: [] };
                rows.set(ticketId, row);
            }
            for (const ref of note.refs) {
                if (ref === ticketId)
                    continue;
                const column = classifyRef(ref, isTicketId);
                if (column !== null && !row[column].includes(ref))
                    row[column].push(ref);
            }
        }
    }
    return [...rows.values()].sort((a, b) => compareCodeUnits(a.id, b.id));
}
// ── Rendered text ───────────────────────────────────────────────────────────────────────────────────────
/**
 * The file name of one ticket's trace. The id is one the board grammar admits (upper-case ASCII letters, digits,
 * one hyphen, at most 26 characters), so it holds no path separator and fits every disk's name limit.
 */
export function traceFileName(id) {
    return `${id}.md`;
}
/** One ticket's trace file: the header, a title, then each column as a bullet list or `None recorded.`. */
export function renderTicketTrace(row) {
    const lines = [TRACE_GENERATED_HEADER, `# Trace: ${row.id}`];
    for (const column of TRACE_COLUMNS) {
        lines.push("", `## ${column}`, "");
        const refs = row[column];
        if (refs.length === 0)
            lines.push("None recorded.");
        else
            for (const ref of refs)
                lines.push(`- ${traceCell(ref)}`);
    }
    return `${lines.join("\n")}\n`;
}
/**
 * The index: the header, a title, one sentence, a blank line, the two-column table header and separator, and
 * one line per ticket linking its trace file, sorted by code-unit order of the id. The sentence avoids every
 * wording HAND_TRACE_PATTERNS finds, and every line fits BUDGETS.indexEntryBytes outside comments
 * (scripts/trace-model.test.ts asserts both through the validator's own rule).
 */
export function renderTraceIndex(rows) {
    const lines = [
        TRACE_GENERATED_HEADER,
        "# Traceability",
        "",
        "Each line links one ticket's trace file. tools/grugops/trace-render.js renders this index from published note refs.",
        "",
        "| Ticket | Trace |",
        "| --- | --- |",
    ];
    const sorted = [...rows].sort((a, b) => compareCodeUnits(a.id, b.id));
    for (const row of sorted)
        lines.push(`| ${row.id} | [${row.id}](${TRACE_LINK_DIR}/${traceFileName(row.id)}) |`);
    return `${lines.join("\n")}\n`;
}
/** A thrown value's own `remedy` property when it is a non-empty string, else null (plan 37-37, IN-11). */
function remedyOf(e) {
    if (typeof e !== "object" || e === null || !Object.hasOwn(e, "remedy"))
        return null;
    const remedy = e.remedy;
    return typeof remedy === "string" && remedy !== "" ? remedy : null;
}
/**
 * Read every task under every context root, in the order given (the live root, then the archive root). A task
 * whose read throws is caught, counted and named in failedTasks, never swallowed; every skip the reader reports
 * is kept with its root and task. How a root is listed, and what an absent root lists, is the caller's io.
 *
 * A failed task is a read failure that stops the render (plan 37-21, D-17, CR-01): it is never read as a task
 * with no notes. The collection reports what was read; whether it is complete enough to plan from is decided
 * by traceReadFailures and planCompleteTraceTree below, the one predicate every caller asks.
 */
export function collectTraceNotes(contextRoots, io) {
    const notes = [];
    const skipped = [];
    const failedTasks = [];
    let tasks = 0;
    for (const root of contextRoots) {
        const listed = [...io.listTasks(root)].sort(compareCodeUnits);
        for (const task of listed) {
            tasks += 1;
            let read;
            try {
                read = io.readTask(task, root);
            }
            catch (e) {
                failedTasks.push({ root, task, reason: e instanceof Error ? e.message : String(e), remedy: remedyOf(e) });
                continue;
            }
            for (const note of read.notes)
                notes.push(note);
            for (const s of read.skipped)
                skipped.push({ root, task, file: s.file, arm: s.arm, detail: s.detail });
        }
    }
    return { tasks, notes, skipped, failedTasks };
}
/**
 * The whole rendered tree: the index at `traceabilityRel`, then one trace file per row under `traceDirRel`, in
 * code-unit order of the id. Keys are repository-relative paths with `/` separators; values are the full text.
 */
export function planTraceTree(rows, traceabilityRel, traceDirRel) {
    const plan = new Map();
    plan.set(traceabilityRel, renderTraceIndex(rows));
    const sorted = [...rows].sort((a, b) => compareCodeUnits(a.id, b.id));
    for (const row of sorted)
        plan.set(`${traceDirRel}/${traceFileName(row.id)}`, renderTicketTrace(row));
    return plan;
}
// ── Was the note read complete? One predicate for every caller (plan 37-21, D-17, READ-1, 33.1 DC-2) ─────────
// A trace file is removed only when a COMPLETE read shows its ticket has no published refs, never because a
// read produced nothing. So the render's write mode, its --check mode and state-check all obtain their plan
// from planCompleteTraceTree, and none of them derives completeness from the counts.
/**
 * The two reader skip arms that are trust decisions: the file is not a sealed note (`unsealed`) or not a note at
 * all (`unparseable`), so leaving it out of the trace is the correct answer, not a gap in the read. Every other
 * reader arm (unopenable, not-a-regular-file, above-ceiling, vanished) is an I/O arm, and every failed task is a
 * failure too: what the note says is unknown, so the read was not complete. An arm missing from this list is a
 * read failure by default, so a new reader arm can never become a silent skip.
 */
export const TRACE_TRUST_SKIP_ARMS = Object.freeze(["unparseable", "unsealed"]);
/**
 * Every read failure of a collection, in collection order: each failed task first, then each skipped note whose
 * arm is not in TRACE_TRUST_SKIP_ARMS. Empty exactly when the read was complete.
 */
export function traceReadFailures(collection) {
    const failures = collection.failedTasks.map((f) => ({
        root: f.root,
        task: f.task,
        file: null,
        arm: null,
        reason: f.reason,
        remedy: f.remedy,
    }));
    for (const s of collection.skipped) {
        if (TRACE_TRUST_SKIP_ARMS.includes(s.arm))
            continue;
        const reason = s.detail !== "" ? s.detail : `the reader could not read it (${s.arm})`;
        failures.push({ root: s.root, task: s.task, file: s.file, arm: s.arm, reason, remedy: null });
    }
    return failures;
}
/**
 * The plan of the rendered tree, given only when the note read was complete (traceReadFailures is empty).
 * With any failure there is no plan, so no caller can compare, write or remove from a partial read. The rows'
 * tickets are what the board grammar's `isTicketId` admits (plan 37-22).
 */
export function planCompleteTraceTree(collection, isTicketId, traceabilityRel, traceDirRel) {
    const failures = traceReadFailures(collection);
    if (failures.length > 0)
        return { complete: false, failures };
    const rows = buildTraceRows(collection.notes, isTicketId);
    return { complete: true, rows, plan: planTraceTree(rows, traceabilityRel, traceDirRel) };
}
// ── Every planned file name is legal before the first write (plan 37-22, D-17, WR-01) ──────────────────────
// A trace file name is decided by a ref a note carries. The render once wrote part of the tree and then met a
// name the disk refused (ENAMETOOLONG), and every later run failed at its pre-write check. So the render checks
// every planned name first, whatever is on disk, and refuses the run when one is not legal.
/**
 * The longest file name the trace writes, in UTF-8 bytes: 255, the longest single name ext4, APFS and NTFS
 * accept. A board identifier is at most 26 characters, so a trace file name is at most 29 bytes.
 */
export const TRACE_FILE_NAME_MAX_BYTES = 255;
/** The UTF-8 length of `s`, in bytes, counted by code point (this module imports nothing). */
function utf8ByteLength(s) {
    let bytes = 0;
    for (const ch of s) {
        const cp = ch.codePointAt(0);
        bytes += cp < 0x80 ? 1 : cp < 0x800 ? 2 : cp < 0x10000 ? 3 : 4;
    }
    return bytes;
}
/**
 * One reason per planned trace file that is not legal, in code-unit order of the key; empty when every one is.
 * A planned key under `<traceDirRel>/` is legal exactly when it equals `<traceDirRel>/<traceFileName(id)>` for an
 * id the board grammar admits (`isTicketId`) and the file name is at most TRACE_FILE_NAME_MAX_BYTES bytes in
 * UTF-8. Keys outside the trace directory (the index) are not trace file names and are not asked.
 */
export function traceFileNameRefusals(plan, traceDirRel, isTicketId) {
    const prefix = `${traceDirRel}/`;
    const reasons = [];
    for (const key of [...plan.keys()].sort(compareCodeUnits)) {
        if (!key.startsWith(prefix))
            continue;
        const name = key.slice(prefix.length);
        const id = name.endsWith(".md") ? name.slice(0, -".md".length) : null;
        if (id === null || !isTicketId(id) || traceFileName(id) !== name) {
            reasons.push(`${key}: the file name is not <ticket identifier>.md for an identifier the board grammar admits`);
        }
        else if (utf8ByteLength(name) > TRACE_FILE_NAME_MAX_BYTES) {
            reasons.push(`${key}: the file name is ${utf8ByteLength(name)} bytes, over the ${TRACE_FILE_NAME_MAX_BYTES}-byte limit`);
        }
    }
    return reasons;
}
// ── The owned tree, collisions and the comparison (plan 37-07, D-01, D-02, research Pitfalls 5 and 11) ──────
// The renderer owns every generated byte and nothing else (D-02: no role writes a trace file by hand). So a
// file is the renderer's to replace or remove only when its first line is TRACE_GENERATED_HEADER; any other
// file is hand-written and stops the run. render and state-check (plan 37-09) both compare through
// compareTraceTree, so the two cannot disagree about what is fresh.
/** The ceiling a trace file is read under. A rendered trace file is a few hundred bytes; 8 MiB is refused. */
export const TRACE_FILE_MAX_BYTES = 8 * 1024 * 1024;
/**
 * The record rule for the trace tree (the plan 37-01 contract): the entries of the trace directory that the
 * renderer considers at all are the names that do not begin with `.`, in code-unit order. A directory keeper
 * (`.gitkeep`) or operating-system metadata (`.DS_Store`) is never read, compared, refused, removed or
 * reported. No ticket identifier begins with `.` (the board grammar's isTicketId), so no generated file is ever
 * outside this set.
 * This module imports nothing, so it states the rule for the tree it checks rather than sharing
 * scripts/state-rules.ts recordEntryNames.
 */
export function ownedTraceEntries(names) {
    return names.filter((n) => !n.startsWith(".")).sort(compareCodeUnits);
}
/**
 * The groups of distinct ticket identifiers whose trace file names are equal once lower-cased. On a
 * case-insensitive disk such a group would write one file over another (research Pitfall 11), so a caller
 * refuses the run. Each group and the list of groups are in code-unit order; no group has fewer than two ids.
 * The board grammar admits upper-case ASCII letters and digits only, so lower-casing is the whole fold, and no
 * two distinct board identifiers fold together (plan 37-22); this stays as a defensive check.
 */
export function caseFoldCollisions(ids) {
    const byFold = new Map();
    for (const id of ids) {
        const fold = traceFileName(id).toLowerCase();
        const group = byFold.get(fold) ?? new Set();
        group.add(id);
        byFold.set(fold, group);
    }
    return [...byFold.values()]
        .filter((g) => g.size > 1)
        .map((g) => [...g].sort(compareCodeUnits))
        .sort((a, b) => compareCodeUnits(a[0], b[0]));
}
/**
 * True when `text` was written by the renderer: its first line is TRACE_GENERATED_HEADER. A CR before the
 * first line feed is accepted, so a checkout that converted line ends still owns its generated files.
 */
export function isGeneratedTraceText(text) {
    const end = text.indexOf("\n");
    const first = end === -1 ? text : text.slice(0, end);
    return (first.endsWith("\r") ? first.slice(0, -1) : first) === TRACE_GENERATED_HEADER;
}
/**
 * Compare the planned tree with the tree under `repoRoot`. Every planned path is read; the trace directory is
 * listed once, and its raw listing goes through ownedTraceEntries before anything else, so a keeper never
 * reaches the read, the hand-written test or the extra set. A present file that is not generated is
 * hand-written; a generated planned file that differs is changed; a generated unplanned file is extra. Paths
 * are composed with `/`, which every platform's file API accepts. Each list is in code-unit order.
 */
export function compareTraceTree(plan, repoRoot, io, traceabilityRel, traceDirRel) {
    const at = (rel) => `${repoRoot}/${rel}`;
    if (!plan.has(traceabilityRel))
        throw new Error(`compareTraceTree: the plan does not hold the index ${traceabilityRel}`);
    const missing = [];
    const extra = [];
    const changed = [];
    const handWritten = [];
    for (const [rel, text] of plan) {
        const onDisk = io.readText(at(rel));
        if (onDisk === null)
            missing.push(rel);
        else if (!isGeneratedTraceText(onDisk))
            handWritten.push(rel);
        else if (onDisk !== text)
            changed.push(rel);
    }
    const listed = io.listDir(at(traceDirRel));
    for (const name of ownedTraceEntries(listed ?? [])) {
        const rel = `${traceDirRel}/${name}`;
        if (plan.has(rel))
            continue;
        const onDisk = io.readText(at(rel));
        if (onDisk === null)
            continue; // gone between the listing and the read: nothing to remove
        if (isGeneratedTraceText(onDisk))
            extra.push(rel);
        else
            handWritten.push(rel);
    }
    for (const list of [missing, extra, changed, handWritten])
        list.sort(compareCodeUnits);
    return { missing, extra, changed, handWritten };
}
