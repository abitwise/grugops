// trace-render.ts — the host trace renderer (phase 37, plan 37-06, SPLIT-03, D-01, D-03).
//
// WHAT IT IS. A kit-shipped runnable in the shape of state-check.ts: authored here, compiled to a committed
// trace-render.js, and run on a host as `node trace-render.js <repo-root>` with only Node present. It reads the
// published notes of every task under the live context root (.grugops/context) and the finished-ticket archive
// root (.grugops/archive/context), and writes one trace file per ticket identifier found in their refs under
// memory-bank/plans/traceability/, plus memory-bank/plans/traceability.md as a one-line-per-ticket index. A
// ticket whose notes sit only in the archive root still gets its trace file and its index line (D-03), so
// moving a finished ticket's context never drops a trace row.
//
// THE D-12 CONTRACT.
//   exit 0 → the trace was rendered: every planned file was written
//   exit 1 → reserved for the read-only check mode plan 37-07 adds; this write mode never exits 1
//   exit 2 → the render could not run: a bad argument, a root that is not a readable directory, a path that
//            resolves outside the repository root, a missing state directory, or an entry at a planned
//            path that is not a regular file. Exit 2 is never a pass: it prints nothing on stdout, and every
//            check that can refuse runs before the first write.
//
// NOTHING IS HIDDEN. Every run prints one summary line on stdout with the number of tasks read, notes read,
// notes skipped under each arm of the note reader (in the reader's own arm order), tasks that could not be
// read, and files written. Each task that could not be read is named on its own line. A skipped note is never
// rendered: the seal check is the reader's, embedded verbatim, and is never re-implemented here.
//
// THE ROOT IS A BOUNDARY. Every path is resolved with realpath before it is used, and a context root, a task's
// notes directory or the trace directory that resolves outside realpath(root) is refused by name. The trace
// directory is created only when absent, after its parent's realpath is confirmed inside the root. An entry at
// a planned path is lstat'ed before anything is written, so a FIFO there is never opened.
//
// EVERY WRITE IS ATOMIC. Each file goes through the embedded atomicWrite (a temp sibling, then a rename), so an
// interrupted render leaves each file either its old or its new bytes. Two renders over the same notes produce
// byte-identical trees, because every sort in the trace model compares code units.
//
// OUTPUT IS SANITIZED. Every value read from the repository (a path, a task name, a reason) has each C0, C1 and
// DEL code point removed by the embedded stripControlChars before it is printed.
//
// BUILTINS ONLY. A host runs this file with no kit and no node_modules, so it imports `node:` builtins and
// nothing else. The hand-written part below imports them as namespaces, so the names the generated region
// imports never collide with its own.
//
// NOTHING HERE IS RETYPED. The state paths, the sanitizer, the trace model and the note read path sit in the
// generated region, copied verbatim from install/state-layout.ts, scripts/state-rules.ts, scripts/trace-model.ts
// and scripts/context-io.ts by scripts/generate-runnable-embeds.ts. scripts/runnable-embeds-freshness.ts fails
// CI when the region differs from a fresh derivation.
//
