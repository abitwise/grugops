// ── The hand-written part: argv, the boundary checks, the reads, the writes and the summary ───────────────
const USAGE = "Usage: node trace-render.js <repo-root>";
/** One value made safe to print: the embedded rule removes every C0, C1 and DEL code point. */
function printable(value) {
    return stripControlChars(value, false);
}
/** The render could not run: one sanitized message on stderr, nothing on stdout, exit 2. Never a pass. */
function couldNotRun(message) {
    process.stderr.write(`Error: ${printable(message)} The trace render did not run.\n`);
    process.exit(2);
}
/** The errno code of a thrown filesystem error, for a message. */
function codeOf(e) {
    return e.code ?? "unknown error";
}
const args = process.argv.slice(2);
const unknownFlag = args.find((a) => a.startsWith("--"));
if (unknownFlag !== undefined)
    couldNotRun(`unknown option ${unknownFlag}. ${USAGE}.`);
const rootArg = args[0];
if (rootArg === undefined)
    couldNotRun(`no repository root was given. ${USAGE}.`);
if (args.length > 1)
    couldNotRun(`more than one repository root was given. ${USAGE}.`);
let root;
try {
    root = nodeFs.realpathSync(rootArg);
}
catch (e) {
    couldNotRun(`the repository root ${rootArg} cannot be resolved (${codeOf(e)}). ${USAGE}.`);
}
try {
    if (!nodeFs.statSync(root).isDirectory())
        couldNotRun(`the repository root ${rootArg} is not a directory. ${USAGE}.`);
    nodeFs.accessSync(root, nodeFs.constants.R_OK | nodeFs.constants.W_OK | nodeFs.constants.X_OK);
}
catch (e) {
    couldNotRun(`the repository root ${rootArg} is not a readable and writable directory (${codeOf(e)}).`);
}
/** True when an already-resolved absolute path is the root or lies under it. */
function insideRoot(real) {
    return real === root || real.startsWith(root + nodePath.sep);
}
/** The absolute path of a repository-relative path with `/` separators. */
function abs(rel) {
    return nodePath.join(root, ...rel.split("/"));
}
/**
 * The real path of an existing directory, or null when nothing is there. Anything else is refused by name:
 * a path that resolves outside the root, a present entry that is not a directory, or one that cannot be
 * resolved. `what` names the path in the refusal.
 */
function realDirectoryOrNull(path, what) {
    let st;
    try {
        st = nodeFs.lstatSync(path);
    }
    catch (e) {
        if (codeOf(e) === "ENOENT")
            return null;
        couldNotRun(`${what} cannot be inspected (${codeOf(e)}).`);
    }
    let real;
    try {
        real = nodeFs.realpathSync(path);
    }
    catch (e) {
        couldNotRun(`${what} cannot be resolved (${codeOf(e)}).`);
    }
    if (!insideRoot(real))
        couldNotRun(`${what} resolves outside the repository root, so it was not used.`);
    if (st.isSymbolicLink())
        st = nodeFs.statSync(real);
    if (!st.isDirectory())
        couldNotRun(`${what} is not a directory.`);
    return real;
}
/** The context roots in reading order: the live root, then the archive root. An absent root is empty. */
const CONTEXT_ROOTS = [CONTEXT_REL, CONTEXT_ARCHIVE_REL].map((rel) => ({ rel, real: realDirectoryOrNull(abs(rel), `the context root ${rel}`) }));
/** The repository-relative name of a context root, for the report. */
function relOfRoot(real) {
    return CONTEXT_ROOTS.find((r) => r.real === real)?.rel ?? real;
}
/** The task directories under one context root, by Dirent, so a symlinked entry is never a task. */
function listTasks(real) {
    return nodeFs
        .readdirSync(real, { withFileTypes: true })
        .filter((e) => e.isDirectory())
        .map((e) => e.name);
}
/**
 * One task's notes, through the embedded walk (its skip arms and its seal check) and the embedded record
 * projection. A notes directory that resolves outside the root throws, so the model counts the task by name.
 */
function readTask(task, real) {
    assertSafeTask(task);
    const notesDir = nodePath.join(real, task, "notes");
    let notesReal = null;
    try {
        notesReal = nodeFs.realpathSync(notesDir);
    }
    catch (e) {
        if (codeOf(e) !== "ENOENT")
            throw new Error(`its notes directory cannot be resolved (${codeOf(e)})`);
    }
    if (notesReal !== null && !insideRoot(notesReal)) {
        throw new Error("its notes directory resolves outside the repository root, so it was not read");
    }
    const read = readRawNotesWithSkips(task, real);
    return {
        notes: read.notes.map((raw) => ({ refs: recordFromParsed(raw.parsed, raw.id).refs })),
        skipped: read.skipped,
    };
}
const present = CONTEXT_ROOTS.flatMap((r) => (r.real === null ? [] : [r.real]));
const collection = collectTraceNotes(present, { listTasks, readTask });
const plan = planTraceTree(buildTraceRows(collection.notes), TRACEABILITY_REL, TRACE_DIR_REL);
// ── Every refusal runs before the first write ─────────────────────────────────────────────────────────
const traceDirAbs = abs(TRACE_DIR_REL);
const stateDirAbs = nodePath.dirname(traceDirAbs);
const stateDirRel = TRACE_DIR_REL.slice(0, TRACE_DIR_REL.lastIndexOf("/"));
const stateDirReal = realDirectoryOrNull(stateDirAbs, `the state directory ${stateDirRel}`);
if (stateDirReal === null)
    couldNotRun(`the state directory ${stateDirRel} does not exist; install grugops first.`);
const traceDirReal = realDirectoryOrNull(traceDirAbs, `the trace directory ${TRACE_DIR_REL}`);
for (const rel of plan.keys()) {
    let st = null;
    try {
        st = nodeFs.lstatSync(abs(rel));
    }
    catch (e) {
        if (codeOf(e) !== "ENOENT")
            couldNotRun(`${rel} cannot be inspected (${codeOf(e)}).`);
    }
    if (st !== null && !st.isFile())
        couldNotRun(`${rel} is present and is not a regular file, so nothing was written.`);
}
// ── The writes ────────────────────────────────────────────────────────────────────────────────────────
try {
    if (traceDirReal === null)
        nodeFs.mkdirSync(traceDirAbs);
}
catch (e) {
    couldNotRun(`the trace directory ${TRACE_DIR_REL} cannot be created (${codeOf(e)}).`);
}
let written = 0;
for (const [rel, text] of plan) {
    try {
        atomicWrite(abs(rel), text);
    }
    catch (e) {
        couldNotRun(`${rel} cannot be written (${codeOf(e)}); ${written} file(s) were written before it.`);
    }
    written += 1;
}
// ── The summary ───────────────────────────────────────────────────────────────────────────────────────
const perArm = NOTE_SKIP_ARMS.map((arm) => `${arm} ${collection.skipped.filter((s) => s.arm === arm).length}`);
const lines = [
    `Rendered the trace: ${collection.tasks} task(s) and ${collection.notes.length} note(s) read; ` +
        `skipped notes: ${perArm.join(", ")}; unreadable tasks ${collection.failedTasks.length}; ` +
        `${written} file(s) written.`,
    ...collection.failedTasks.map((f) => `UNREADABLE TASK ${printable(relOfRoot(f.root))}/${printable(f.task)}: ${printable(f.reason)}`),
];
process.stdout.write(`${lines.join("\n")}\n`);
process.exit(0);
