/**
 * The note read was not complete (plan 37-21, D-17, CR-01, READ-1): a task could not be read, or a note was
 * skipped under an I/O arm. In both modes, before any compare, pre-write check or write: one sanitized line on
 * stderr with the counts, one line per failure naming it, nothing on stdout, exit 2. A compare over a partial
 * read is not a compare (D-12), and the write mode never removes a trace file because a read produced nothing.
 */
function couldNotRunIncomplete(failures: readonly TraceReadFailure[]): never {
  const tasks = failures.filter((f) => f.file === null).length;
  const notes = failures.length - tasks;
  const lines = [
    `Error: the notes could not be read completely (${tasks} task(s) and ${notes} note(s) could not be read), so ` +
      "the trace was not compared or rendered and nothing was written or removed. The trace render did not run.",
    ...failures.map((f) => {
      const at = `${printable(relOfRoot(f.root))}/${printable(f.task)}`;
      return f.file === null
        ? `UNREADABLE TASK ${at}: ${printable(f.reason)}`
        : `UNREADABLE NOTE ${at}/notes/${printable(f.file)} (${printable(f.arm ?? "")}): ${printable(f.reason)}`;
    }),
  ];
  process.stderr.write(`${lines.join("\n")}\n`);
  process.exit(2);
}

