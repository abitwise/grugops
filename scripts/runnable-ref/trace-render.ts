// trace-render.ts — the host trace renderer (phase 37, plans 37-06 and 37-07, SPLIT-03, D-01, D-02, D-03).
//
// WHAT IT IS. A kit-shipped runnable in the shape of state-check.ts: authored here, compiled to a committed
// trace-render.js, and run on a host as `node trace-render.js <repo-root> [--check]` with only Node present. It
// reads the published notes of every task under the live context root (.grugops/context) and the
// finished-ticket archive root (.grugops/archive/context). The write mode makes memory-bank/plans/traceability/
// hold one trace file per ticket identifier found in their refs, and memory-bank/plans/traceability.md a
// one-line-per-ticket index. A ticket whose notes sit only in the archive root still gets its trace file and its
// index line (D-03), so moving a finished ticket's context never drops a trace row. `--check` compares the tree
// with a fresh render and writes nothing.
//
// THE D-12 CONTRACT.
//   exit 0 → write mode: the tree now equals a fresh render (missing and changed files written, extra generated
//            files removed). --check: the index and every owned file in the trace directory equal a fresh
//            render.
//   exit 1 → a finding, and nothing was written. In both modes: a hand-written index or trace file (its first
//            line is not the generated header), or two ticket identifiers whose file names fold to one name on
//            a case-insensitive disk. Under --check also: each missing, extra or changed file, named.
//   exit 2 → the run could not run: a bad argument, a root that is not a readable directory, a context root
//            that cannot be listed, a context root, state directory or trace directory that cannot be inspected,
//            a symbolic link at a context root, the state directory or the trace directory or at any component of
//            the path to one below the repository root, present or dangling, whatever its target (plan 37-33,
//            D-20, CR-05), a symbolic link at any component of the path to a trace file or the index below the
//            repository root, present or dangling, whatever its target (plan 37-34, D-20), a path that resolves
//            outside the repository root, a listed trace-directory name the state layout cannot hold (a
//            backslash in it), a missing state directory,
//            an entry at a compared path that is not a regular file, a file the reader refuses, or an unexpected
//            error, which is reported on stderr by name (with the files already written and removed, when the
//            write section had started) and never surfaces as Node's own exit 1 (plan 37-20). In both modes
//            exit 2 also covers a note read that was not complete (plan 37-21, CR-01): a task whose notes
//            could not be read, or a note skipped under an I/O arm (unopenable, not-a-regular-file,
//            above-ceiling, vanished), each named on stderr; nothing is compared, written or removed. A
//            context-root entry that is not a task directory (a symbolic link of any kind, a regular file, a
//            FIFO), or that vanished after the listing, and a `notes` link whose target cannot be reached, are
//            such failed tasks too (plan 37-28, D-18, CR-03, CR-04), named on stderr. In both
//            modes exit 2 also covers a planned trace file name that is not `<ticket identifier>.md` for an
//            identifier the board grammar admits, within the file-name limit (plan 37-22, WR-01), checked before
//            the first lstat or write. Exit 2 is never a pass: it prints nothing on stdout, and every check that
//            can refuse runs before the first write.
//
// THE RENDERER OWNS GENERATED BYTES AND NOTHING ELSE (D-01, D-02). A file is replaced or removed only when its
// first line is the generated header; anything else stops the run before any write. Directory keepers and
// operating-system metadata (names beginning with `.`) are never read, compared, removed or reported: the
// trace model's ownedTraceEntries is the one owner of that rule, and the write mode acts only on the sets the
// model's compareTraceTree returns.
//
// NOTHING IS HIDDEN. Every run that does not exit 2 prints one summary line on stdout with the number of tasks
// read, notes read, notes skipped under each arm of the note reader (in the reader's own arm order), tasks that
// could not be read, and, in the write mode, files written and removed. Only the two trust arms (unparseable,
// unsealed) can be non-zero there: whether a read was complete is decided by the embedded trace model's
// planCompleteTraceTree, the one predicate state-check asks too, and an incomplete read is exit 2 with each
// task and note named on stderr. A skipped note is never rendered: the seal check is the reader's, embedded
// verbatim, and is never re-implemented here. Every entry of a context root is a task, a keeper or a failed task:
// keepers (a regular file whose name begins with `.`, such as `.gitkeep`) are the one entry kind that is neither a
// task nor a failure, and they are never read or counted (plan 37-28, D-18).
//
// THE ROOT IS A BOUNDARY. The root is resolved once, with realpath, before any state read; every other position is
// repository-relative below it. Below the real root, no component of the path to a context root, the state
// directory, the trace directory, a trace file or the index is followed if it is a symbolic link: each is asked of the
// generated rootChainPresence (plans 37-33 and 37-34, D-20, CR-05), which lstat's every component, so a link there,
// present or dangling, whatever its target, inside the root or outside it, is refused by name (exit 2) from the lstat
// alone, and nothing is written or removed. A trace file or the index is asked with leaf `entry`: a link at it is a
// present entry that is not a regular file, refused by name (a dangling one because its target cannot be reached).
// Only an lstat ENOENT on a component whose earlier components are real directories is absence, so a context root
// beneath a link is never read as an absent root and no trace file is removed because of one. A path whose real path
// is outside the root is refused by name. A link above the root (macOS `/tmp` to `/private/tmp`) is resolved with the
// root and never seen. Which composed path is under the root is the generated isWithin's answer, the one boundary
// predicate (37-REVIEW.md IN-13): this file keeps no boundary test of its own. The trace directory is created only
// when absent and a trace file is to be written, after it and its parents were verified above. Every compared path is
// lstat'ed before it is opened, so a FIFO is never opened. Below a context root, the task and notes positions keep
// plan 37-28's rules (D-18): the task position never follows a link (a context-root entry that is a symbolic link is
// a failed task, CR-04), absence there is the generated entryPresence's answer, asked through the generated
// readTaskNoteRefs and listContextTasks, and a task's notes directory that resolves outside the root is refused.
//
